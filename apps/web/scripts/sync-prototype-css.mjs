// Copies the approved prototype CSS (design/everyfield-marketing.html) into src/styles/prototype.css.
// Run from apps/web: `node scripts/sync-prototype-css.mjs`. `--check` exits 1 when the file is out of date.
// Kept out: the prototype control bar, the toast and the screenshot hook (body.shot). Fonts come from next/font.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const html = readFileSync(here("../../../design/everyfield-marketing.html"), "utf8");
const block = (id) => {
  const m = html.match(new RegExp(`<style id="${id}">\\n([\\s\\S]*?)</style>`));
  if (!m) throw new Error(`style block ${id} not found in the prototype`);
  return m[1];
};

const PROTOTYPE_ONLY = /\.pbar|\.toast|body\.shot|body\.pbar-hidden|Prototype control bar|body \{ padding-bottom: 118px; \}/;

function strip(css) {
  const lines = css.split("\n").filter((l) => !PROTOTYPE_ONLY.test(l));
  // Drop media blocks left empty by the filter.
  const out = [];
  for (const line of lines) {
    if (/^\s*\}\s*$/.test(line) && out.length && /^@media[^{]*\{\s*$/.test(out[out.length - 1])) {
      out.pop();
      continue;
    }
    out.push(line);
  }
  return out.join("\n");
}

const tokens = block("mk-tokens")
  .replace('"Bricolage Grotesque", ui-sans-serif', "var(--font-bricolage), ui-sans-serif")
  .replace('"Instrument Sans", ui-sans-serif', "var(--font-instrument), ui-sans-serif");
if (!tokens.includes("var(--font-bricolage)") || !tokens.includes("var(--font-instrument)")) {
  throw new Error("font tokens changed shape in the prototype; update sync-prototype-css.mjs");
}

const css =
  "/* Generated by scripts/sync-prototype-css.mjs from design/everyfield-marketing.html. Do not edit by hand. */\n" +
  tokens + "\n" + strip(block("mk-site"));

const target = here("../src/styles/prototype.css");
if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== css) {
    console.error("src/styles/prototype.css is out of date. Run node scripts/sync-prototype-css.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(target, css);
  console.log(`wrote ${target}`);
}
