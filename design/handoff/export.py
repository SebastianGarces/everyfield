#!/usr/bin/env python3
"""Export handoff files from the prototype.

Reads the :root and [data-theme="dark"] token blocks and the gradient-card
tones from design/everyfield-ui.html and writes design/handoff/tokens.css.
Also writes the brand mark and wordmark to design/handoff/assets/ as SVG,
components.md from the prototype's Inventory table, and fills empty screen-map
ownership cells from the feature catalog. The --check mode also
confirms that every prototype route is listed in screens.md, that every feature
with a route in docs/catalog/features.json has a status in the screen-to-feature
map, and that each not-drawn row names only packages that own one of its features.

Usage:
  python3 design/handoff/export.py          # write all generated files
  python3 design/handoff/export.py --check  # fail if any output is stale
"""
import html as htmllib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / "everyfield-ui.html"
TARGET = HERE / "tokens.css"
ASSETS = HERE / "assets"
SYMBOLS = {"ef-mark": "everyfield-mark.svg", "ef-wordmark": "everyfield-wordmark.svg", "ef-lockup": "everyfield-lockup.svg"}


def block(css, selector):
    start = css.index(selector + " {")
    end = css.index("\n}", start)
    return css[start:end]


def tokens(text):
    out = {}
    for name, value in re.findall(r"--ef-([a-z0-9-]+):\s*([^;]+);", text):
        out[name] = " ".join(value.split())
    return out


def gradient_tones(css):
    tones = {}
    for tone, body in re.findall(r'\.insight\[data-tone="([a-z]+)"\]\s*\{([^}]*)\}', css):
        vals = dict(re.findall(r"--(g-base|g[1-5]):\s*([^;]+);", body))
        if vals:
            tones[tone] = vals
    return tones


def corners(css):
    """The --corner-* shape variables that the --ef-radius-* tokens read (declarations only)."""
    return dict(re.findall(r"(--corner-[a-z]+):\s*([^;]+);", css))


def render(css):
    light = tokens(block(css, ":root"))
    shape = corners(css)
    dark = tokens(block(css, '[data-theme="dark"]'))
    tones = gradient_tones(css)

    def decls(d, indent="  "):
        return "\n".join(f"{indent}--ef-{k}: {v};" for k, v in d.items())

    hue_map = []
    for k in light:
        m = re.fullmatch(r"(green|blue|magenta|amber|violet|teal|sky|sage|rose)-(\d+|display)", k)
        if m:
            hue_map.append(f"  --color-{k}: var(--ef-{k});")
    plain_colors = ["ink", "ink-2", "cream", "green", "text", "text-2", "text-3", "focus", "canvas", "frame",
                    "surface", "surface-2", "surface-3", "surface-raised", "line", "line-2", "on-ink", "on-ink-soft", "hover"]
    color_map = [f"  --color-{k}: var(--ef-{k});" for k in plain_colors if k in light]
    radius_map = [f"  --radius-{k[7:]}: var(--ef-{k});" for k in light if k.startswith("radius-")]
    shadow_map = [f"  --shadow-{k[7:]}: var(--ef-{k});" for k in light if k.startswith("shadow-")]
    text_map = [f"  --text-{k[5:]}: var(--ef-{k});" for k in light if re.fullmatch(r"text-(xs|sm|md|lg)", k)]
    text_map += [f"  --text-{k}: var(--ef-{k});" for k in light if re.match(r"(title|display)-", k)]
    grad = []
    for tone, vals in tones.items():
        for k, v in vals.items():
            grad.append(f"  --ef-grad-{tone}-{k.replace('g-', '')}: {v.strip()};")

    return f"""/* Everyfield design tokens for Tailwind CSS v4.
   GENERATED by design/handoff/export.py from design/everyfield-ui.html.
   Do not edit by hand: change the prototype, then run the script.

   Layers:
   1. --ef-* variables: the source values, light in :root, dark in [data-theme="dark"].
      Use next-themes with attribute="data-theme".
   2. shadcn/ui semantic variables (--background, --primary, ...) mapped to --ef-*.
   3. @theme inline: Tailwind utilities (bg-surface, text-text-2, rounded-card, shadow-card,
      font-display, bg-green-500 ...) that follow the active theme.

   This file holds tokens only. The consuming stylesheet imports Tailwind first, so Tailwind
   resolves from the app that depends on it:
     @import "tailwindcss";
     @import "<path>/design/handoff/tokens.css"; */

:root {{
  /* Corner shape: every radius token reads these. All corners are square. */
{chr(10).join(f"  {k}: {v};" for k, v in shape.items())}
{decls(light)}

  /* Gradient card tones (InsightCard). Light and dark use the same values. */
{chr(10).join(grad)}

  /* shadcn/ui semantic names */
  --background: var(--ef-frame);
  --foreground: var(--ef-text);
  --card: var(--ef-surface);
  --card-foreground: var(--ef-text);
  --popover: var(--ef-surface-raised);
  --popover-foreground: var(--ef-text);
  --primary: var(--ef-ink);
  --primary-foreground: var(--ef-on-ink);
  --secondary: var(--ef-surface-2);
  --secondary-foreground: var(--ef-ink);
  --muted: var(--ef-surface-2);
  --muted-foreground: var(--ef-text-2);
  --accent: var(--ef-surface-3);
  --accent-foreground: var(--ef-ink);
  --destructive: var(--ef-magenta-600);
  --border: var(--ef-line);
  --input: var(--ef-line-2);
  --ring: var(--ef-focus);
  --radius: var(--ef-radius-md);
}}

[data-theme="dark"] {{
{decls(dark)}
}}

@theme inline {{
  --font-display: var(--ef-font-display);
  --font-title: var(--ef-font-title);
  --font-sans: var(--ef-font-body);
{chr(10).join(color_map)}
{chr(10).join(hue_map)}
  --color-background: var(--background);
  --color-foreground: var(--foreground);
  --color-card: var(--card);
  --color-card-foreground: var(--card-foreground);
  --color-popover: var(--popover);
  --color-popover-foreground: var(--popover-foreground);
  --color-primary: var(--primary);
  --color-primary-foreground: var(--primary-foreground);
  --color-secondary: var(--secondary);
  --color-secondary-foreground: var(--secondary-foreground);
  --color-muted: var(--muted);
  --color-muted-foreground: var(--muted-foreground);
  --color-accent: var(--accent);
  --color-accent-foreground: var(--accent-foreground);
  --color-destructive: var(--destructive);
  --color-border: var(--border);
  --color-input: var(--input);
  --color-ring: var(--ring);
{chr(10).join(text_map)}
{chr(10).join(radius_map)}
{chr(10).join(shadow_map)}
  --ease-slide: var(--ef-slide-ease);
  --container-content: var(--ef-content-max);
  --container-content-wide: var(--ef-content-max-wide);
}}

@media (prefers-reduced-motion: reduce) {{
  :root {{ --ef-slide-dur: 0s; }}
}}
"""


def symbols(html):
    found = {sid: re.search(r'<symbol id="%s" viewBox="([^"]+)">(.*?)</symbol>' % sid, html, re.S) for sid in SYMBOLS}

    def inline(use):
        """Replace <use href="#sym"> with a nested <svg>, so each file stands alone."""
        ref = found[use.group(1)]
        attrs = use.group(2).strip().rstrip("/").strip()
        inner = " ".join(line.strip() for line in ref.group(2).strip().splitlines())
        return f'<svg viewBox="{ref.group(1)}" {attrs}>{inner}</svg>'

    files = {}
    for sid, name in SYMBOLS.items():
        m = found[sid]
        text = re.sub(r'<use href="#([a-z-]+)"([^>]*)>', inline, m.group(2))
        body = "\n".join("  " + line.strip() for line in text.strip().splitlines())
        files[ASSETS / name] = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{m.group(1)}" fill="none">\n'
                                f'  <!-- Everyfield brand. Paths use currentColor: set color to ink #181D19 or cream #F6F0E9; new-growth #1AF197 only as a tile behind an ink symbol. -->\n'
                                f'{body}\n</svg>\n')
    return files


COMPONENTS = HERE / "components.md"
SCREENS = HERE / "screens.md"

COMPONENT_INTRO = """# Components

GENERATED by `design/handoff/export.py` from the Inventory page of the prototype (`#/inventory`).
Do not edit the table by hand. Change the Inventory in `design/everyfield-ui.html`, then run the script.

## How to build them

Components live in `packages/ui` (see `docs/architecture/README.md`). Start each one from the shadcn/ui component named in the last column when there is one, then restyle it with the tokens in [`tokens.css`](tokens.css). "none" means a plain styled element with no behavior primitive. Keep the prototype's names as the React component names, so search finds both.

Rules that apply to every component:

- Variants are props, not separate components. Use class-variance-authority for the variant classes.
- Every interactive part is a real `button` or `a`, with the focus ring from [foundations.md](foundations.md#accessibility-rules).
- Every component that loads data has a loading, error and empty state drawn from `StatePanel`, `Skeleton` and `EmptyState`.
- Text on a hue fill is ink, never white.
- Shared hover and active highlights use one `HoverGroup` per list, menu, table, nav or tab set. In React, Motion's `layoutId` gives the same sliding effect.

## Inventory

| Group | Component | Code name | Parts | Variants and props | Primitive |
|---|---|---|---|---|---|
"""


def components(html):
    rows = []
    for tr in re.findall(r'<tr><td class="faint t-sm">.*?</tr>', html):
        cells = re.findall(r"<td[^>]*>(.*?)</td>", tr)
        if len(cells) != 6:
            continue
        def clean(x):
            x = re.sub(r"<[^>]+>", " ", x)
            x = htmllib.unescape(" ".join(x.split()))
            return x.replace("|", "\\|")
        g, name, code, parts, variants, prim = (clean(c) for c in cells)
        names = re.sub(r"<[^>]+>", " ", cells[2])
        code = " ".join(f"`{c}`" for c in re.findall(r"<[^<>]+>", htmllib.unescape(names)))
        rows.append(f"| {g} | {name} | {code} | {parts} | {variants} | {prim} |")
    return COMPONENT_INTRO + "\n".join(rows) + f"\n\n{len(rows)} components.\n", len(rows)


def routes(html):
    pages = re.findall(r'<section class="page[^"]*" data-page="([a-z-]+)"', html)
    detail = re.findall(r"'([a-z0-9/-]+)': \['([a-z-]+)'", re.search(r"const DETAIL = \{(.*?)\};", html, re.S).group(1))
    by_page = {page: sub for sub, page in detail}
    out = []
    for p in pages:
        if p == "stub":
            continue
        out.append("#/" + by_page.get(p, p))
    out += ["#/settings/" + s for s in re.findall(r'data-settings-nav="([a-z]+)"', html)]
    return out


FEATURES = HERE.parent.parent / "docs" / "catalog" / "features.json"
ID = re.compile(r"\b((?:REQ-)?[A-Z]+-\d{3})(?: to ([A-Z]+-\d{3}))?")


STATUSES = ("designed", "not designed", "future feature")


def expand(text):
    ids = []
    for first, last in ID.findall(text):
        if not last:
            ids.append(first)
            continue
        prefix, start = first.rsplit("-", 1)
        ids += [f"{prefix}-{n:03d}" for n in range(int(start), int(last.rsplit("-", 1)[1]) + 1)]
    return ids


def screen_owners(screens):
    """Fill missing owners from the catalog, preserving annotated owner cells."""
    features = {f["id"]: f for f in json.loads(FEATURES.read_text(encoding="utf-8"))}
    start, end = screens.find("## Screen-to-feature map"), screens.find("## Design system pages")
    if start < 0 or end < 0:
        return screens
    rows = []
    for line in screens[start:end].splitlines(keepends=True):
        cells = line.split("|")
        if line.startswith("|") and len(cells) == 6 and not cells[3].strip():
            ids = [i for i in expand(cells[2]) if i in features]
            owners = sorted({wp for i in ids for wp in features[i]["work_packages"]})
            cells[3] = " " + (", ".join(owners) if owners else "none in v3") + " "
            line = "|".join(cells)
        rows.append(line)
    return screens[:start] + "".join(rows) + screens[end:]


def feature_map(screens):
    """Return problems in the screen-to-feature map compared with the catalog."""
    features = {f["id"]: f for f in json.loads(FEATURES.read_text(encoding="utf-8"))}
    start, end = screens.find("## Screen-to-feature map"), screens.find("## Design system pages")
    if start < 0 or end < 0:
        return ["screens.md has no screen-to-feature map"]
    mapped, problems = set(), []
    for line in screens[start:end].splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if not line.startswith("|") or len(cells) < 3 or set(cells[1]) <= set("-") or cells[-1] == "Status":
            continue
        ids = [i for i in expand(cells[1]) if not i.startswith("REQ-")]
        unknown = [i for i in ids if i not in features]
        if unknown:
            problems.append(f"unknown feature IDs in map row '{cells[0]}': {', '.join(unknown)}")
        routed = [i for i in ids if i in features and features[i]["routes"]]
        if routed and not re.match(r"(?:not designed|designed)\b", cells[-1]):
            problems.append(f"routed features {', '.join(routed)} have invalid status '{cells[-1]}' in map row '{cells[0]}'; use designed or not designed")
        elif not cells[-1].startswith(STATUSES):
            problems.append(f"map row '{cells[0]}' has status '{cells[-1]}'; start it with one of: {', '.join(STATUSES)}")
        mapped.update(ids)
        if len(cells) == 4:
            owners = {wp for i in ids if i in features for wp in features[i]["work_packages"]}
            extra = [wp for wp in expand(cells[2]) if wp not in owners]
            if extra:
                problems.append(f"map row '{cells[0]}' names packages that own none of its features: {', '.join(extra)}")
    missing = sorted(k for k, f in features.items() if f["routes"] and k not in mapped)
    if missing:
        problems.append("routed features with no status in the screen-to-feature map: " + ", ".join(missing))
    return problems


def main():
    html = SOURCE.read_text(encoding="utf-8")
    comp_md, comp_count = components(html)
    outputs = {TARGET: render(html), **symbols(html), COMPONENTS: comp_md}
    screens = SCREENS.read_text(encoding="utf-8") if SCREENS.exists() else ""
    outputs[SCREENS] = screen_owners(screens)
    if "--check" in sys.argv:
        stale = [p.name for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        missing = [r for r in routes(html) if f"`{r}`" not in screens]
        map_problems = feature_map(screens)
        if stale or missing or map_problems:
            if stale:
                print("Out of date: " + ", ".join(stale) + ". Run: python3 design/handoff/export.py")
            if missing:
                print("Routes missing from screens.md: " + ", ".join(missing))
            for problem in map_problems:
                print("Screen map: " + problem)
            return 1
        print(f"Up to date: tokens.css ({outputs[TARGET].count('--ef-')} --ef- references), "
              f"{len(SYMBOLS)} brand assets, components.md ({comp_count} components), "
              f"screens.md ({len(routes(html))} routes, every routed feature mapped).")
        return 0
    ASSETS.mkdir(exist_ok=True)
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
        print(f"Wrote {path.relative_to(HERE.parent.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
