CREATE FUNCTION settings_update_name(handle uuid,new_name text) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT AS $$
DECLARE subject uuid;
BEGIN
 SELECT a.id INTO subject FROM auth_session s JOIN account a ON a.auth_user_id=s.user_id WHERE s.id=handle AND s.expires_at>clock_timestamp() FOR UPDATE OF a;
 IF subject IS NULL OR length(btrim(new_name)) NOT BETWEEN 1 AND 200 OR EXISTS(SELECT FROM lifecycle_witness WHERE kind='account' AND opaque_subject_id=subject AND state NOT IN ('active','cancelled')) THEN RAISE EXCEPTION 'unavailable' USING ERRCODE='42501'; END IF;
 UPDATE auth_user SET name=btrim(new_name),updated_at=clock_timestamp() WHERE id=(SELECT auth_user_id FROM account WHERE id=subject);
END $$;
REVOKE ALL ON FUNCTION settings_update_name(uuid,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION settings_update_name(uuid,text) TO everyfield_runtime;
CREATE FUNCTION settings_suspend_subject(witness uuid,request uuid) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT AS $$
DECLARE w lifecycle_witness%ROWTYPE;
BEGIN
 SELECT * INTO w FROM lifecycle_witness WHERE id=witness AND request_id=request AND state='pending_deletion' FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'unavailable' USING ERRCODE='42501'; END IF;
 DELETE FROM auth_session WHERE user_id IN (SELECT auth_user_id FROM account WHERE id=w.account_id OR id IN (SELECT account_id FROM seat WHERE plant_id=w.plant_id AND ended_at IS NULL));
 UPDATE mail SET cancel_requested_at=coalesce(cancel_requested_at,clock_timestamp()),state=CASE WHEN state='pending' THEN 'cancelled' ELSE state END WHERE tenant_id=w.opaque_subject_id OR recipient_account_id=w.account_id;
 UPDATE job SET state='cancelled',finished_at=clock_timestamp(),lease_owner=NULL,lease_until=NULL,claim_generation=claim_generation+1 WHERE tenant_id=w.opaque_subject_id AND state IN ('ready','retry_wait','claimed') AND kind<>'lifecycle_purge';
END $$;
REVOKE ALL ON FUNCTION settings_suspend_subject(uuid,uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION settings_suspend_subject(uuid,uuid) TO everyfield_runtime;
CREATE FUNCTION settings_purge_subject(witness uuid,request uuid,expected bigint) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT AS $$
DECLARE w lifecycle_witness%ROWTYPE; done timestamptz;
BEGIN
 SELECT * INTO w FROM lifecycle_witness WHERE id=witness AND request_id=request AND request_revision=expected AND state='purging' AND cancel_until<=clock_timestamp() FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'unavailable' USING ERRCODE='42501'; END IF;
 PERFORM settings_purge_content(witness,request,expected);
 IF EXISTS(SELECT FROM file_object WHERE tenant_id=w.opaque_subject_id AND state<>'purged') THEN RAISE EXCEPTION 'incomplete_byte_cleanup' USING ERRCODE='23514'; END IF;
 done=clock_timestamp();
 UPDATE lifecycle_witness SET state='purged',cleanup_state='confirmed',live_purged_at=done,copy_expires_at=done+interval '168 hours',witness_checkpoint=witness_checkpoint+1 WHERE id=witness;
END $$;
REVOKE ALL ON FUNCTION settings_purge_subject(uuid,uuid,bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION settings_purge_subject(uuid,uuid,bigint) TO everyfield_cleanup;

