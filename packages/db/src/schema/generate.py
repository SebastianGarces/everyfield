"""Render reviewed baseline DDL. Run with --check to detect catalog drift."""
import argparse
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
CATALOG = json.loads((ROOT / 'docs/schema/target.json').read_text())
EXISTING = {'early_access_request', 'early_access_attempt', 'schema_migration'}
q = lambda s: '"' + s.replace('"', '""') + '"'

def render():
    out = ['-- Generated by packages/db/src/schema/generate.py. Review this SQL with target.json.',
           '-- Existing 0001 and its ledger are preserved. The runner provides transaction + migration lock.',
           'CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;']
    tables = [t for t in CATALOG['tables'] if t['name'] not in EXISTING]
    for t in tables:
        columns = []
        for c in t['columns']:
            typ = 'public.vector' if c['type'] == 'vector' else c['type']
            default = {'server-generated UUID': 'gen_random_uuid()', 'transaction UTC instant': 'now()'}.get(c.get('default'), c.get('default'))
            columns.append(q(c['name']) + ' ' + typ + ('' if c['nullable'] else ' NOT NULL') + (' DEFAULT ' + default if default else ''))
        if t['primary_key']:
            columns.append('PRIMARY KEY (' + ', '.join(map(q, t['primary_key'])) + ')')
        for i, key in enumerate(t['unique_keys']):
            if not key.get('where') and key['columns'] != t['primary_key']:
                columns.append(f'CONSTRAINT {q(t["name"]+"_uq_"+str(i))} UNIQUE (' + ', '.join(map(q, key['columns'])) + ')')
        for i, check in enumerate(t['checks']):
            if t.get('library_owned'):
                if not re.search(r'[=<>]|\bin \(', check): continue
            check = re.sub(r'\binterval\b(?!\s*\')', '"interval"', check) if t['name'] == 'recurrence' else check
            columns.append(f'CONSTRAINT {q(t["name"]+"_ck_"+str(i))} CHECK ({check})')
        if t['name'] == 'auth_user': columns.append('CHECK (email = lower(btrim(email)))')
        out.append('CREATE TABLE ' + q(t['name']) + ' (\n  ' + ',\n  '.join(columns) + '\n);')
        for i, key in enumerate(t['unique_keys']):
            if key.get('where'):
                out.append(f'CREATE UNIQUE INDEX {q(t["name"]+"_uq_"+str(i))} ON {q(t["name"])} (' + ', '.join(map(q,key['columns'])) + ') WHERE ' + key['where'] + ';')
    for t in tables:
        for i, fk in enumerate(t['foreign_keys']):
            out.append(f'ALTER TABLE {q(t["name"])} ADD CONSTRAINT {q(t["name"]+"_fk_"+str(i))} FOREIGN KEY (' + ', '.join(map(q,fk['columns'])) + ') REFERENCES ' + q(fk['references']['table']) + ' (' + ', '.join(map(q,fk['references']['columns'])) + ') ON DELETE ' + fk.get('on_delete','restrict').upper().replace('_',' ') + (' DEFERRABLE INITIALLY DEFERRED;' if fk['references']['table']=='record' or (t['name'] in ['account','plant','organization'] and fk['references']['table']=='tenant') else ' DEFERRABLE INITIALLY IMMEDIATE;'))
            # Support dependency-ordered cleanup and parent FK checks without table scans.
            if not any(k['columns'][:len(fk['columns'])] == fk['columns'] for k in t['unique_keys']) and t['primary_key'][:len(fk['columns'])] != fk['columns']:
                out.append(f'CREATE INDEX {q(t["name"]+"_ref_"+str(i))} ON {q(t["name"])} (' + ', '.join(map(q,fk['columns'])) + ');')
    out += ["INSERT INTO tenant(id,kind) VALUES ('00000000-0000-0000-0000-000000000000','global');"]
    # Named canonical spellings are pinned to Node 24 ICU; aliases normalize at the boundary.
    zones = json.loads(subprocess.check_output(['node','--input-type=module','-e',"console.log(JSON.stringify(['UTC',...Intl.supportedValuesOf('timeZone')]))"], text=True))
    allowed = ','.join("'"+z+"'" for z in sorted(set(zones)))
    for t in tables:
        for c in t['columns']:
            if c['name'] in ['timezone','personal_timezone','pending_timezone','meeting_timezone']:
                out.append(f'ALTER TABLE {q(t["name"])} ADD CONSTRAINT {q(t["name"]+"_"+c["name"]+"_iana")} CHECK ({q(c["name"])} IN ({allowed}));')
    # Each subtype binds exactly one identity to its actual owner. No body-free row grants access.
    for t in tables:
        name = t['name']
        if not any(f['references']['table']=='record' and f['columns'][0]=='id' for f in t['foreign_keys']): continue
        cols = {c['name'] for c in t['columns']}
        special = {'account':'NEW.id','plant':'NEW.id','organization':'NEW.id','seat':'coalesce(NEW.plant_id,NEW.organization_id)',
                   'affiliation':'coalesce(NEW.plant_id,NEW.account_id,NEW.sending_church_id)',
                   'feedback_publication':"coalesce(NEW.account_id, '00000000-0000-0000-0000-000000000000'::uuid)",
                   'lifecycle_witness':"coalesce(NEW.account_id,NEW.plant_id, '00000000-0000-0000-0000-000000000000'::uuid)"}
        owner = special.get(name)
        if owner is None:
            owner = next(('NEW.'+c for c in ['tenant_id','plant_id','organization_id','account_id'] if c in cols), "'00000000-0000-0000-0000-000000000000'::uuid")
        root = name in ['account','plant','organization']
        root_sql = f"INSERT INTO tenant(id,kind) VALUES (NEW.id,'{name}') ON CONFLICT DO NOTHING; IF NOT EXISTS(SELECT FROM tenant WHERE id=NEW.id AND kind='{name}') THEN RAISE EXCEPTION 'root_kind_mismatch' USING ERRCODE='23514'; END IF;" if root else ''
        retain = name in ['feedback_publication','lifecycle_witness']
        owner_sql = f"IF TG_OP='UPDATE' THEN SELECT tenant_id INTO actual_owner FROM record WHERE id=OLD.id; ELSE actual_owner := {owner}; END IF;" if retain else f'actual_owner := {owner};'
        out.append(f"""CREATE FUNCTION {q(name+'_bind_record')}() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path FROM CURRENT AS $$
DECLARE actual_owner uuid;
BEGIN
  {owner_sql}
  {root_sql}
  IF TG_OP='UPDATE' AND NEW.id <> OLD.id THEN RAISE EXCEPTION 'immutable_record_id' USING ERRCODE='23514'; END IF;
  INSERT INTO record(id,kind,tenant_id) VALUES (NEW.id,'{name}',actual_owner) ON CONFLICT DO NOTHING;
  PERFORM 1 FROM record WHERE id=NEW.id AND kind='{name}' AND tenant_id=actual_owner FOR KEY SHARE;
  IF NOT FOUND THEN RAISE EXCEPTION 'record_subtype_owner_mismatch' USING ERRCODE='23514'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER bind_record AFTER INSERT OR UPDATE ON {q(name)} FOR EACH ROW EXECUTE FUNCTION {q(name+'_bind_record')}();""")
    out.append('''CREATE FUNCTION assert_record_binding() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE actual_id uuid; actual_owner uuid;
BEGIN
  EXECUTE format('SELECT id, %s FROM %I.%I WHERE id=$1',TG_ARGV[0],TG_TABLE_SCHEMA,TG_TABLE_NAME) INTO actual_id,actual_owner USING NEW.id;
  IF actual_id IS NULL THEN RETURN NULL; END IF;
  IF NOT EXISTS(SELECT FROM record WHERE id=actual_id AND kind=TG_TABLE_NAME AND tenant_id=actual_owner) THEN
    RAISE EXCEPTION 'deferred_record_binding_mismatch' USING ERRCODE='23514';
  END IF;
  RETURN NULL;
END $$;''')
    for t in tables:
        name=t['name']
        if not any(f['references']['table']=='record' and f['columns'][0]=='id' for f in t['foreign_keys']): continue
        cols={c['name'] for c in t['columns']}
        owner={'account':'id','plant':'id','organization':'id','seat':'coalesce(plant_id,organization_id)',
               'affiliation':'coalesce(plant_id,account_id,sending_church_id)'}.get(name)
        if name in ['feedback_publication','lifecycle_witness']:
            owner=f'(SELECT tenant_id FROM record WHERE record.id={q(name)}.id)'
        if owner is None: owner=next((q(c) for c in ['tenant_id','plant_id','organization_id','account_id'] if c in cols), "'00000000-0000-0000-0000-000000000000'::uuid")
        arg=owner.replace("'","''")
        out.append(f"CREATE CONSTRAINT TRIGGER assert_record_binding AFTER INSERT OR UPDATE ON {q(name)} DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION assert_record_binding('{arg}');")
    references = []
    for t in tables:
        for fk in t['foreign_keys']:
            if fk['references']['table'] != 'file_object': continue
            col = fk['columns'][0]
            references.append(f'SELECT 1 FROM {q(t["name"])} WHERE {q(col)} = object_id')
            out.append(f"CREATE TRIGGER {q('file_ready_'+col)} BEFORE INSERT OR UPDATE OF {q(col)} ON {q(t['name'])} FOR EACH ROW EXECUTE FUNCTION require_ready_file('{col}');")
    # File binding and cleanup take conflicting locks on the same immutable file row.
    ready_function = '''CREATE FUNCTION require_ready_file() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE object_id uuid;
BEGIN
  object_id := (to_jsonb(NEW)->>TG_ARGV[0])::uuid;
  IF object_id IS NOT NULL THEN
    PERFORM 1 FROM file_object WHERE id=object_id AND state='ready' FOR SHARE;
    IF NOT FOUND THEN RAISE EXCEPTION 'file_not_ready' USING ERRCODE='23514'; END IF;
  END IF;
  RETURN NEW;
END $$;'''
    # Install the function before its referencing triggers.
    trigger_start = next(i for i,v in enumerate(out) if v.startswith('CREATE TRIGGER "file_ready_'))
    out.insert(trigger_start,ready_function)
    out.append('CREATE FUNCTION file_is_referenced(object_id uuid) RETURNS boolean LANGUAGE sql STABLE SET search_path FROM CURRENT AS $$ SELECT EXISTS (' + ' UNION ALL '.join(references) + ') $$;')
    out.append((Path(__file__).parent/'integrity.sql').read_text())
    out.append((Path(__file__).parent/'roles.sql').read_text())
    return '\n\n'.join(out)+'\n'

if __name__ == '__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    path=ROOT/'packages/db/migrations/0002_baseline.sql'; sql=render()
    file_table=next(t for t in CATALOG['tables'] if t['name']=='file_object')
    types={'uuid':'string','text':'string','bigint':'string','timestamptz':'Date'}
    fields=[]
    for column in file_table['columns']:
        values=CATALOG['type_contracts'].get('file_object.'+column['name'])
        typ=' | '.join(json.dumps(value) for value in values) if isinstance(values,list) else types[column['type']]
        fields.append('  '+column['name']+': '+typ+(' | null' if column['nullable'] else '')+';')
    row='// Generated from docs/schema/target.json by generate.py.\nexport interface FileObjectRow {\n'+'\n'.join(fields)+'\n}\n'
    row_path=Path(__file__).parent/'file.generated.ts'
    if args.check:
        if row_path.read_text()!=row: raise SystemExit('File row type differs from schema catalog.')
    else: row_path.write_text(row)
    if args.check:
        if path.read_text()!=sql: raise SystemExit('Baseline SQL differs; run packages/db/src/schema/generate.py and review the diff.')
        print('Baseline DDL matches reviewed catalog and integrity rules.')
    else: path.write_text(sql)
