"""Generate operation identity only. Domain producers register exact predicates separately."""
import argparse,json
from pathlib import Path
root=Path(__file__).resolve().parents[4]
ops=json.loads((root/'docs/catalog/operations.json').read_text())['operations']
rows={o['id']:{'kind':'write' if o['kind']=='command' else 'read','model':o['model_tool']} for o in ops if not o['id'].startswith('privateCare.')}
text='// Generated by packages/domain/src/access/generate.py.\nexport const operationRegistry = '+'{\n'+''.join('  '+json.dumps(k)+': '+json.dumps(v,separators=(',', ':'))+',\n' for k,v in sorted(rows.items()))+'}'+' as const;\n'
p=Path(__file__).parent/'operations.generated.ts'
a=argparse.ArgumentParser();a.add_argument('--check',action='store_true');args=a.parse_args()
if args.check:
 if p.read_text()!=text:raise SystemExit('Access operation registry differs; rerun generator.')
else:p.write_text(text)
