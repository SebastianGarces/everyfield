// Derive closed names from the reviewed physical/operation catalogs. No runtime
// import of the full schema into clients. Run with --check in test:unit.
import { readFileSync, writeFileSync } from "node:fs";
const schema = JSON.parse(readFileSync(new URL("../../../../docs/schema/target.json", import.meta.url), "utf8"));
const operations = JSON.parse(
	readFileSync(new URL("../../../../docs/catalog/operations.json", import.meta.url), "utf8"),
);
function literals(table, column) {
	const check = schema.tables.find((t) => t.name === table).checks.find((c) => c.startsWith(`${column} in (`));
	return [...check.matchAll(/'([^']+)'/g)].map((m) => m[1]);
}
const text =
	"// Generated by sync-vocabulary.mjs from the current catalogs.\n" +
	[
		["recordKinds", literals("record", "kind")],
		["auditActions", literals("audit_event", "action")],
		// privacy_exclusion elsewhere describes model projections, not a receipt ban.
		["sharedOperationNames", operations.operations.filter((o) => !o.id.startsWith("privateCare.")).map((o) => o.id)],
	]
		.map(([name, values]) => `export const ${name} = ${JSON.stringify(values, null, 2)} as const;\n`)
		.join("");
const target = new URL("./vocabulary.ts", import.meta.url);
if (process.argv.includes("--check")) {
	if (readFileSync(target, "utf8") !== text) throw new Error("Shared vocabulary drift; run sync-vocabulary.mjs");
} else writeFileSync(target, text);
